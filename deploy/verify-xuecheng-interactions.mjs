import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function verifyEditorInteractions({ page, api, base, outputDir, waitFor }) {
  const doc = await api('/docs', 'POST', { title: 'Interaction QA', content: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Toolbar target' }] }] } })
  await page.goto(`${base}/editor/#/doc/${doc.id}`)
  const pm = page.getByRole('textbox', { name: '文档正文' })
  const toolbar = page.getByRole('toolbar', { name: '文档工具栏' })
  await pm.waitFor()
  assert.equal(await toolbar.getByRole('button', { name: '撤销', exact: true }).isDisabled(), true)
  await pm.press('ControlOrMeta+A')
  await toolbar.getByRole('button', { name: '加粗', exact: true }).click()
  assert.equal(await pm.locator('strong').innerText(), 'Toolbar target')
  await pm.press('ControlOrMeta+z')
  assert.equal(await pm.locator('strong').count(), 0)
  await pm.press('ControlOrMeta+Shift+z')
  assert.equal(await pm.locator('strong').innerText(), 'Toolbar target')
  await pm.press('Alt+F10')
  assert.ok(await toolbar.evaluate(el => el.contains(document.activeElement)))
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  // Roving focus skips disabled redo, then reaches the paragraph menu.
  await toolbar.getByRole('button', { name: '段落格式', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  const formats = page.getByRole('menu', { name: '段落格式' })
  await formats.waitFor()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  assert.equal(await pm.locator('h6').innerText(), 'Toolbar target')
  await pm.press('ControlOrMeta+Alt+0')
  assert.equal(await pm.locator('h6').count(), 0)
  await toolbar.getByRole('button', { name: '文字颜色', exact: true }).click()
  await page.getByRole('menu', { name: '文字颜色' }).getByRole('menuitem', { name: '颜色 #d93026' }).click()
  assert.equal(await pm.locator('span[style*="color"]').innerText(), 'Toolbar target')
  await pm.press('ControlOrMeta+\\')
  assert.equal(await pm.locator('strong, span[style*="color"]').count(), 0)
  console.log('PASS toolbar selection, undo/redo, keyboard navigation, headings, colors and clear formatting')

  await pm.press('ControlOrMeta+A')
  await pm.press('ControlOrMeta+k')
  const link = page.getByRole('dialog', { name: '编辑链接' })
  await link.getByLabel('链接地址', { exact: true }).fill('javascript:alert(1)')
  await link.getByRole('button', { name: '应用', exact: true }).click()
  await link.getByRole('alert').waitFor()
  await link.getByLabel('链接地址', { exact: true }).fill('https://example.com/docs')
  await link.getByRole('button', { name: '应用', exact: true }).click()
  assert.equal(await pm.locator('a').innerText(), 'Toolbar target')
  await pm.press('ArrowLeft')
  await waitFor(() => page.evaluate(() => window.__pmView.state.selection.empty), 'ArrowLeft did not collapse the selection after link editing')
  await pm.press('ControlOrMeta+k')
  assert.equal(await link.getByLabel('链接地址', { exact: true }).inputValue(), 'https://example.com/docs')
  await link.getByRole('button', { name: '移除链接' }).click()
  assert.equal(await pm.locator('a').count(), 0)
  await pm.press('ControlOrMeta+A')
  await pm.press('ControlOrMeta+Shift+9')
  assert.equal(await pm.locator('ul[data-task-list] li').count(), 1)
  await pm.press('ArrowRight')
  await pm.press('Enter')
  await page.keyboard.insertText('second task')
  assert.equal(await pm.locator('ul[data-task-list] li').count(), 2)
  await toolbar.getByRole('button', { name: '有序列表', exact: true }).click()
  assert.equal(await pm.locator('ol > li').count(), 2)
  assert.ok((await pm.innerText()).includes('Toolbar target'))
  await pm.press('Tab')
  assert.equal(await pm.locator('ol ol').count(), 1)
  await pm.press('Shift+Tab')
  assert.equal(await pm.locator('ol ol').count(), 0)
  console.log('PASS link editing/validation, list conversion and list indentation shortcuts')

  await page.evaluate(async () => navigator.clipboard.write([new ClipboardItem({
    'text/plain': new Blob(['plain pasted'], { type: 'text/plain' }),
    'text/html': new Blob(['<b>plain pasted</b>'], { type: 'text/html' }),
  })]))
  await pm.press('ControlOrMeta+A'); await pm.press('Shift+F10')
  await page.getByRole('menuitem', { name: '粘贴为纯文本', exact: true }).click()
  await waitFor(async () => (await pm.innerText()).trim() === 'plain pasted', 'Plain clipboard paste failed')
  assert.equal(await pm.locator('strong').count(), 0)
  await pm.press('ControlOrMeta+A')
  await page.evaluate(() => {
    window.originalClipboardWrite = navigator.clipboard.write.bind(navigator.clipboard)
    navigator.clipboard.write = () => new Promise(resolve => { window.finishClipboardWrite = resolve })
  })
  await pm.press('Shift+F10'); await page.getByRole('menuitem', { name: '剪切', exact: true }).click()
  await pm.press('ArrowRight')
  await page.evaluate(async () => {
    window.finishClipboardWrite()
    navigator.clipboard.write = window.originalClipboardWrite
    delete window.originalClipboardWrite; delete window.finishClipboardWrite
    await new Promise(resolve => setTimeout(resolve, 50))
  })
  assert.equal((await pm.innerText()).trim(), 'plain pasted')
  console.log('PASS plain clipboard paste and delayed cut selection guard')

  // Fresh simple document for Markdown, slash menu and soft breaks.
  const writing = await api('/docs', 'POST', { title: 'Writing QA' })
  await page.goto(`${base}/editor/#/doc/${writing.id}`); await pm.waitFor(); await pm.click()
  await page.keyboard.type('**bold**')
  assert.equal(await pm.innerText(), 'bold')
  assert.equal(await pm.locator('strong').innerText(), 'bold')
  await pm.press('ControlOrMeta+A'); await pm.press('Backspace')
  await page.keyboard.type('x*x*')
  assert.equal(await pm.textContent(), 'xx')
  assert.equal(await pm.locator('em').innerText(), 'x')
  await pm.press('ControlOrMeta+A'); await page.keyboard.insertText('line')
  await pm.press('Shift+Enter'); await page.keyboard.insertText('next')
  assert.equal(await pm.locator('p').count(), 1)
  assert.equal(await pm.locator('br').count(), 1)
  await pm.press('ControlOrMeta+A'); await page.keyboard.insertText('/zzzz')
  await page.locator('.slash-empty').waitFor()
  await pm.press('ArrowDown'); await pm.press('ArrowUp'); await pm.press('Escape')
  await page.locator('.slash-menu').waitFor({ state: 'hidden' })
  await pm.press('ControlOrMeta+A'); await page.keyboard.insertText('/')
  await page.locator('.slash-menu').waitFor()
  await pm.press('ArrowDown'); await pm.press('Enter')
  assert.equal(await pm.locator('h1').count(), 1)
  assert.equal(await pm.textContent(), '')
  await pm.press('ControlOrMeta+Alt+0')
  await toolbar.getByRole('button', { name: '插入表格', exact: true }).click()
  await waitFor(async () => (await pm.locator('table').count()) === 1, 'Table not inserted')
  await page.locator('.ctx-bar').waitFor()
  assert.equal(await page.locator('.ctx-bar').getByRole('button', { name: '拆分单元格', exact: true }).isDisabled(), true)
  await pm.locator('td').last().click()
  await waitFor(() => page.evaluate(() => { const {$from} = window.__pmView.state.selection; return $from.depth === 4 && $from.index(1) === 2 && $from.index(2) === 2 }), 'Click did not select the final table cell')
  await page.keyboard.press('Tab')
  assert.equal(await pm.locator('tr').count(), 4)
  await pm.press('Shift+Tab')
  await pm.press('Shift+F10')
  const menu = page.getByRole('menu', { name: '编辑操作' })
  await menu.waitFor()
  assert.equal(await menu.getByRole('menuitem', { name: '合并单元格', exact: true }).isDisabled(), true)
  await menu.getByRole('menuitem', { name: '快捷键速查', exact: true }).click()
  await page.getByRole('dialog', { name: '快捷键速查' }).waitFor()
  await page.screenshot({ path: join(outputDir, 'shortcuts.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: '快捷键速查' }).waitFor({ state: 'hidden' })
  console.log('PASS Markdown without duplication, slash empty results, soft breaks, table Tab and context help')

  await page.getByRole('button', { name: '切换到黑夜模式' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await toolbar.getByRole('button', { name: '字号', exact: true }).click()
  const sizes = page.getByRole('menu', { name: '字号' })
  const bounds = await sizes.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844)
  await page.screenshot({ path: join(outputDir, 'toolbar-mobile-dark.png'), fullPage: true })
  await sizes.getByRole('menuitem', { name: '24', exact: true }).click()
  await pm.press('ControlOrMeta+s')
  await page.locator('.save-state').filter({ hasText: '已保存' }).waitFor()
  await page.reload(); await pm.waitFor()
  assert.equal(await pm.locator('tr').count(), 4)
  console.log('PASS mobile dropdown bounds, dark mode, save shortcut and reload')

  await page.setViewportSize({ width: 1440, height: 1000 })
  const paragraph = text => ({ type: 'paragraph', content: [{ type: 'text', text }] })
  const blocks = await api('/docs', 'POST', { title: 'Block QA', content: { type: 'doc', content: ['alpha', 'beta', 'gamma'].map(paragraph) } })
  await page.goto(`${base}/editor/#/doc/${blocks.id}`); await pm.waitFor()
  await pm.locator('p').first().click()
  await pm.locator('p').nth(1).hover()
  await page.getByTitle('块操作', { exact: true }).hover()
  await page.locator('.bh-menu').getByRole('button', { name: '复制', exact: true }).click()
  assert.deepEqual(await pm.locator('p').allTextContents(), ['alpha', 'beta', 'beta', 'gamma'])
  await page.route('**/editor-qa-image.svg', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="120" height="60"><rect width="120" height="60" fill="#4a9bff"/></svg>' }))
  await toolbar.getByRole('button', { name: '插入图片', exact: true }).click()
  const picture = page.getByRole('dialog', { name: '插入图片' })
  await picture.getByLabel('图片地址', { exact: true }).fill(`${base}/editor-qa-image.svg`)
  await picture.getByRole('button', { name: '应用', exact: true }).click()
  await pm.locator('img[src]').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '删除图片', exact: true }).click()
  assert.equal(await pm.locator('img[src]').count(), 0)
  await pm.press('ControlOrMeta+z')
  assert.equal(await pm.locator('img[src]').count(), 1)
  console.log('PASS hovered block targeting, image dialog/context delete and undo')

  const cell = text => ({ type: 'table_cell', content: [paragraph(text)] })
  const table = await api('/docs', 'POST', { title: 'Cell QA', content: { type: 'doc', content: [{ type: 'table', content: [
    { type: 'table_row', content: [cell('a'), cell('b')] }, { type: 'table_row', content: [cell('c'), cell('d')] },
  ] }] } })
  await page.goto(`${base}/editor/#/doc/${table.id}`); await pm.locator('td').last().waitFor()
  await pm.locator('td').nth(0).click()
  await pm.locator('td').nth(2).click({ modifiers: ['Shift'] })
  assert.equal(await pm.locator('.selectedCell').count(), 2)
  await pm.locator('td').nth(0).click({ button: 'right' })
  assert.equal(await pm.locator('.selectedCell').count(), 2)
  await page.screenshot({ path: join(outputDir, 'table-context-dark.png'), fullPage: true })
  await page.getByRole('menuitemcheckbox', { name: '加粗', exact: true }).click()
  assert.deepEqual(await pm.locator('td strong').allTextContents(), ['a', 'c'])
  await pm.press('Shift+F10')
  await page.getByRole('menuitem', { name: '合并单元格', exact: true }).click()
  assert.equal(await pm.locator('td[rowspan="2"]').count(), 1)
  await pm.press('Shift+F10')
  await page.getByRole('menuitem', { name: '拆分单元格', exact: true }).click()
  assert.equal(await pm.locator('td').count(), 4)
  console.log('PASS rectangular cell context selection, formatting, merge and split')
}
